"""Frozen oracle for QuantumErrorDecoder (hidden from the agent).

Decode rotated surface-code memory experiments generated by Stim. The candidate receives a
graphlike detector error model and a batch of syndrome (detection-event) bitstrings, and must
predict the logical observable flips. The score is the log-scaled reduction in logical error
rate between a trivial decoder that never predicts a flip and minimum-weight perfect matching
(PyMatching), the community-standard decoder.

Better-than-MWPM decoders exist in the literature (belief-propagation variants, correlated
matching, neural decoders), so the score is uncapped: matching MWPM scores 1.0 and beating it
scores above 1.0.

Circuit generation, noise sampling and the MWPM reference are all seeded and deterministic.
"""

from __future__ import annotations

import math
import sys

import numpy as np

# Instances are generated from a difficulty level rather than hardcoded, so a regime that
# saturates can be answered by turning a knob instead of rebuilding the task. This matters
# because the anchor is recomputed by PyMatching at evaluation time: raising DIFFICULTY moves
# the instances and the reference together, with no external record table to look up.
#
# Difficulty raises the code distance, which grows the detector graph roughly as d^2 and makes
# matching harder, and pushes the noise strength toward the circuit-level threshold near 1%.
#
# Shot counts trade two constraints. Statistically the anchor must fail often enough for the
# log-ratio score to be stable; at level 1 the counts below give 105/80/472/40 measured anchor
# failures, holding score noise near or below 4%. Computationally the whole evaluation, candidate
# decoding included, must fit the harness default 300 s timeout - a competent but unvectorized
# decoder is orders of magnitude slower than the reference, so shots shrink as distance grows to
# keep total decode work roughly constant.
DIFFICULTY = 1

_DEV_SHAPE = ((0, 0.005), (1, 0.005), (1, 0.010), (2, 0.005))
_SEALED_SHAPE = ((1, 0.007), (2, 0.008))


def _regimes(level: int, shape, base_seed: int, base_shots: int, prefix: str = ""):
    """Derive concrete regimes from a difficulty level.

    ``shape`` gives each regime as (distance_offset, noise). Level 1 reproduces the original
    hand-picked instances exactly, so raising DIFFICULTY is the only thing that changes them.
    """
    out = []
    for index, (offset, noise) in enumerate(shape):
        base_distance = 3 + 2 * offset
        distance = base_distance + 2 * (int(level) - 1)
        # Decode work per shot grows with the detector count, itself about d^2. Scale relative to
        # this regime's own level-1 distance so level 1 keeps the calibrated shot counts exactly,
        # and only a harder level trades shots for size. Too few shots is not a cheap harder
        # task: it makes the anchor fail single-digit times and the measurement becomes noise.
        shots = max(2000, int(round(base_shots * (base_distance / distance) ** 2)))
        out.append({
            "key": "%sd%d_p%.3f" % (prefix, distance, noise),
            "distance": distance,
            "noise": noise,
            "shots": shots,
            "seed": base_seed + index,
        })
    return tuple(out)


# Development regimes visible in `combined_score`.
DEV_INSTANCES = _regimes(DIFFICULTY, _DEV_SHAPE, 20260807, 6000)

# Evaluator-only regimes reported as `robustness_score`; never returned to the search state.
# Both sit at noise strengths absent from the development set. A larger distance at low noise was
# tried and rejected: at d=9, p=0.004 the anchor fails on roughly 0.2% of shots, so an affordable
# shot count leaves single-digit failure counts and the measurement is noise.
SEALED_INSTANCES = _regimes(DIFFICULTY, _SEALED_SHAPE, 771103, 4000, prefix="sealed_")

# A candidate that imports the reference decoder or the circuit simulator is not solving the
# decoding problem; it is calling the anchor. Treated as an invalid submission.
FORBIDDEN_MODULES = ("pymatching", "stim")

_CACHE: dict = {}


def _build_circuit(distance: int, noise: float):
    import stim

    return stim.Circuit.generated(
        "surface_code:rotated_memory_z",
        distance=distance,
        rounds=distance,
        after_clifford_depolarization=noise,
        before_measure_flip_probability=noise,
        after_reset_flip_probability=noise,
        before_round_data_depolarization=noise,
    )


def _graphlike_errors(circuit) -> list[dict]:
    """Flatten the decomposed detector error model into graphlike components.

    Each returned component has at most two detectors, which is the representation matching
    decoders consume.
    """
    dem = circuit.detector_error_model(decompose_errors=True).flattened()
    out: list[dict] = []
    for inst in dem:
        if inst.type != "error":
            continue
        prob = float(inst.args_copy()[0])
        dets: list[int] = []
        obs: list[int] = []
        groups: list[tuple[list[int], list[int]]] = []
        for target in inst.targets_copy():
            if target.is_separator():
                groups.append((dets, obs))
                dets, obs = [], []
            elif target.is_relative_detector_id():
                dets.append(int(target.val))
            elif target.is_logical_observable_id():
                obs.append(int(target.val))
        groups.append((dets, obs))
        for group_dets, group_obs in groups:
            if not group_dets and not group_obs:
                continue
            out.append(
                {
                    "p": prob,
                    "dets": sorted(group_dets),
                    "obs": sorted(group_obs),
                }
            )
    return out


def _instance_data(spec: dict) -> dict:
    """Build, sample and reference-decode one regime. Cached per process."""
    key = spec["key"]
    if key in _CACHE:
        return _CACHE[key]

    import pymatching

    circuit = _build_circuit(spec["distance"], spec["noise"])
    sampler = circuit.compile_detector_sampler(seed=spec["seed"])
    detectors, observables = sampler.sample(spec["shots"], separate_observables=True)
    detectors = np.ascontiguousarray(detectors, dtype=bool)
    observables = np.ascontiguousarray(observables, dtype=bool)

    dem = circuit.detector_error_model(decompose_errors=True)
    matcher = pymatching.Matching.from_detector_error_model(dem)
    mwpm_prediction = np.asarray(matcher.decode_batch(detectors), dtype=bool)

    trivial_ler = float(observables.any(axis=1).mean())
    mwpm_ler = float((mwpm_prediction != observables).any(axis=1).mean())

    data = {
        "key": key,
        "problem": {
            "num_detectors": int(circuit.num_detectors),
            "num_observables": int(circuit.num_observables),
            "distance": int(spec["distance"]),
            "rounds": int(spec["distance"]),
            "errors": _graphlike_errors(circuit),
        },
        "detectors": detectors,
        "observables": observables,
        "trivial_ler": trivial_ler,
        "mwpm_ler": mwpm_ler,
        "shots": int(spec["shots"]),
    }
    _CACHE[key] = data
    return data


def _log_floor(shots: int) -> float:
    """Resolution floor so a zero-error batch cannot produce an infinite score."""
    return 1.0 / (2.0 * shots)


def _progress(cand_ler: float, trivial_ler: float, mwpm_ler: float, shots: int) -> float:
    floor = _log_floor(shots)
    cand = max(cand_ler, floor)
    trivial = max(trivial_ler, floor)
    mwpm = max(mwpm_ler, floor)
    span = math.log(trivial) - math.log(mwpm)
    if span <= 0.0:
        return 0.0
    progress = (math.log(trivial) - math.log(cand)) / span
    # Uncapped above: beating the MWPM anchor is a real result and must be representable.
    return float(max(0.0, progress))


class _ImportBlocker:
    """Raises on any attempt to import a forbidden module while the candidate runs."""

    def find_module(self, fullname, path=None):  # legacy hook, kept for older loaders
        return self.find_spec(fullname, path)

    def find_spec(self, fullname, path=None, target=None):
        root = fullname.split(".", 1)[0]
        if root in FORBIDDEN_MODULES:
            raise ImportError(f"import of '{fullname}' is not permitted in a candidate decoder")
        return None


def _preloaded_forbidden(decode) -> list[str]:
    """Detect forbidden modules already bound in the candidate module's globals.

    Catches a top-level ``import pymatching`` that ran before the blocker was installed.
    """
    import types

    found: set[str] = set()
    for value in getattr(decode, "__globals__", {}).values():
        if isinstance(value, types.ModuleType):
            root = getattr(value, "__name__", "").split(".", 1)[0]
            if root in FORBIDDEN_MODULES:
                found.add(root)
    return sorted(found)


def _score_instance(data: dict, decode) -> dict:
    problem = {
        "num_detectors": data["problem"]["num_detectors"],
        "num_observables": data["problem"]["num_observables"],
        "distance": data["problem"]["distance"],
        "rounds": data["problem"]["rounds"],
        "errors": [dict(e) for e in data["problem"]["errors"]],
    }
    detectors = data["detectors"].copy()
    observables = data["observables"]
    shots, num_obs = observables.shape

    preloaded = _preloaded_forbidden(decode)
    if preloaded:
        return {
            "key": data["key"],
            "valid": False,
            "reason": f"forbidden module bound in candidate: {','.join(preloaded)}",
            "score": 0.0,
        }

    # Python resolves ``sys.modules`` before ``sys.meta_path``, so modules the evaluator has
    # already imported must be hidden for the duration of the candidate call. The evaluator
    # keeps its own references, so removing the cache entries is safe.
    blocker = _ImportBlocker()
    hidden = {
        name: module
        for name, module in sys.modules.items()
        if name.split(".", 1)[0] in FORBIDDEN_MODULES
    }
    for name in hidden:
        del sys.modules[name]
    sys.meta_path.insert(0, blocker)
    try:
        raw = decode(problem, detectors)
    except Exception as exc:  # noqa: BLE001 - candidate faults are scored, not raised
        return {
            "key": data["key"],
            "valid": False,
            "reason": "raised: %s" % type(exc).__name__,
            "score": 0.0,
        }
    finally:
        try:
            sys.meta_path.remove(blocker)
        except ValueError:
            pass
        sys.modules.update(hidden)

    try:
        pred = np.asarray(raw)
    except Exception as exc:  # noqa: BLE001
        return {"key": data["key"], "valid": False,
                "reason": "bad array: %s" % type(exc).__name__, "score": 0.0}
    if pred.ndim == 1 and num_obs == 1:
        pred = pred.reshape(-1, 1)
    if pred.shape != (shots, num_obs):
        return {
            "key": data["key"],
            "valid": False,
            "reason": f"expected {(shots, num_obs)}, got {tuple(pred.shape)}",
            "score": 0.0,
        }
    if pred.dtype.kind not in "biu":
        if pred.dtype.kind != "f" or not np.all(np.isfinite(pred)):
            return {
                "key": data["key"],
                "valid": False,
                "reason": f"non-binary dtype {pred.dtype}",
                "score": 0.0,
            }
        if not np.all(np.isin(pred, (0.0, 1.0))):
            return {
                "key": data["key"],
                "valid": False,
                "reason": "float predictions must be exactly 0.0 or 1.0",
                "score": 0.0,
            }
    pred = pred.astype(bool)

    cand_ler = float((pred != observables).any(axis=1).mean())
    score = _progress(cand_ler, data["trivial_ler"], data["mwpm_ler"], data["shots"])
    return {
        "key": data["key"],
        "valid": True,
        "logical_error_rate": round(cand_ler, 6),
        "trivial_ler": round(data["trivial_ler"], 6),
        "mwpm_ler": round(data["mwpm_ler"], 6),
        "beats_mwpm": bool(cand_ler < data["mwpm_ler"]),
        "score": score,
    }


def evaluate(decode) -> dict:
    dev = [_score_instance(_instance_data(spec), decode) for spec in DEV_INSTANCES]
    dev_valid = [r for r in dev if r.get("valid")]
    all_valid = len(dev_valid) == len(dev)
    combined = float(np.mean([r["score"] for r in dev])) if dev else 0.0

    sealed_score = 0.0
    sealed: list[dict] = []
    if all_valid:
        sealed = [_score_instance(_instance_data(spec), decode) for spec in SEALED_INSTANCES]
        sealed_score = float(np.mean([r["score"] for r in sealed])) if sealed else 0.0

    return {
        "combined_score": combined,
        "valid": 1.0 if all_valid else 0.0,
        "feasibility_rate": len(dev_valid) / len(dev),
        "robustness_score": sealed_score,
        "beats_mwpm_count": sum(1 for r in dev if r.get("beats_mwpm")),
        "per_instance": dev,
        "sealed_per_instance": sealed,
    }
