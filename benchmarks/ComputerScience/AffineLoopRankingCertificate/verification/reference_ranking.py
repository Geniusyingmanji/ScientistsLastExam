"""Truth-blind catalog of 1-norm ranking directions. Does not import the evaluator."""
from fractions import Fraction


def _fraction(value):
    if isinstance(value, int):
        return Fraction(value, 1)
    numerator, denominator = value
    return Fraction(int(numerator), int(denominator))


def _vector(raw):
    return [_fraction(item) for item in raw]


def _dot(left, right):
    return sum(a * b for a, b in zip(left, right))


def _farkas(linear, constant, guards, lambdas):
    acc = [Fraction(0)] * len(linear)
    offset = Fraction(0)
    for lam, (slope, intercept) in zip(lambdas, guards):
        if lam < 0:
            return False
        for index in range(len(linear)):
            acc[index] += lam * slope[index]
        offset += lam * intercept
    return acc == list(linear) and constant - offset >= 0


def _one_norm(vector):
    return sum(abs(item) for item in vector)


def _pad(values, dimension):
    padded = list(values) + [Fraction(0)] * dimension
    return padded[:dimension]


CATALOG = (
    (Fraction(1), Fraction(0), Fraction(0)),
    (Fraction(0), Fraction(1), Fraction(0)),
    (Fraction(0), Fraction(0), Fraction(1)),
    (Fraction(1, 2), Fraction(1, 2), Fraction(0)),
    (Fraction(1, 3), Fraction(1, 3), Fraction(1, 3)),
    (Fraction(2, 3), Fraction(1, 3), Fraction(0)),
    (Fraction(3, 4), Fraction(1, 4), Fraction(0)),
)

RATES = (
    Fraction(4),
    Fraction(3),
    Fraction(2),
    Fraction(1),
    Fraction(1, 2),
    Fraction(1, 3),
    Fraction(1, 10000),
)


def _lambdas_for(ranking, guards):
    """Unique combination when there are as many independent guards as coordinates.

    Axis-aligned x_i >= 1 gives lambda = r. The skew instance is the 2-by-2
    cone generated by (1,0) and (2,1).
    """
    dimension = len(ranking)
    if len(guards) != dimension:
        return None
    # G^T lambda = r, G rows are guard slopes. For small n, try the product
    # cone by forward substitution when G is triangular, else skip.
    slopes = [slope for slope, _ in guards]
    # Solve by enumerating that our catalog vectors are nonnegative combinations
    # we can invert when G is invertible with rationals.
    # Build G^T.
    gt = [[slopes[i][j] for i in range(dimension)] for j in range(dimension)]
    # 2x2 or 3x3 Cramer's rule.
    det = _det(gt)
    if det == 0:
        return None
    lambdas = []
    for col in range(dimension):
        replaced = [row[:] for row in gt]
        for row in range(dimension):
            replaced[row][col] = ranking[row]
        lambdas.append(_det(replaced) / det)
    if any(value < 0 for value in lambdas):
        return None
    return lambdas


def _det(matrix):
    n = len(matrix)
    if n == 1:
        return matrix[0][0]
    if n == 2:
        return matrix[0][0] * matrix[1][1] - matrix[0][1] * matrix[1][0]
    if n == 3:
        a, b, c = matrix[0]
        d, e, f = matrix[1]
        g, h, i = matrix[2]
        return a * (e * i - f * h) - b * (d * i - f * g) + c * (d * h - e * g)
    raise ValueError("catalog only handles dimension <= 3")


def build_ranking(instance):
    _ = instance["name"]
    _ = instance["max_numerator"]
    _ = instance["max_denominator"]
    dimension = int(instance["dimension"])
    guards = [
        (_vector(item["g"]), _fraction(item["d"]))
        for item in instance["guards"]
    ]
    update_b = _vector(instance["b"])
    update_a = [[_fraction(cell) for cell in row] for row in instance["A"]]
    zeros = [Fraction(0)] * len(guards)
    best = None
    for raw in CATALOG:
        ranking = _pad(raw, dimension)
        if _one_norm(ranking) != 1:
            continue
        lambdas = _lambdas_for(ranking, guards)
        if lambdas is None:
            continue
        if not _farkas(ranking, Fraction(0), guards, lambdas):
            continue
        transposed = [
            sum(update_a[k][j] * ranking[k] for k in range(dimension))
            for j in range(dimension)
        ]
        linear_dec = [ranking[j] - transposed[j] for j in range(dimension)]
        for delta in RATES:
            constant_dec = -_dot(ranking, update_b) - delta
            if not _farkas(linear_dec, constant_dec, guards, zeros):
                continue
            if best is None or delta > best[2]:
                best = (ranking, lambdas, delta)
            break
    if best is None:
        ranking = _pad((Fraction(1),), dimension)
        lambdas = _pad((Fraction(1),), len(guards))
        delta = Fraction(1, 10000)
    else:
        ranking, lambdas, delta = best
    return {
        "r": [[item.numerator, item.denominator] for item in ranking],
        "s": [0, 1],
        "delta": [delta.numerator, delta.denominator],
        "nonneg_lambdas": [[item.numerator, item.denominator] for item in lambdas],
        "decrease_lambdas": [[0, 1] for _ in guards],
    }
